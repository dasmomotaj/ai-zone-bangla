def get_quiz(lesson_id):
    """Return quiz data for a lesson."""
    return QUIZ_BANK.get(
        int(lesson_id),
        {
            "title": "",
            "questions": [],
        },
    )


def quiz_count():
    """Return total number of lessons in the quiz bank."""
    return len(QUIZ_BANK)


